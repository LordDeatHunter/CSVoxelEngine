<script setup lang="ts">
import { onBeforeUnmount, onMounted, ref } from 'vue'
import { withBase } from 'vitepress'
import { buildTree, type TreeData, type TreeScene } from './tree3d.ts'

const props = defineProps<{ id: string }>()

const host = ref<HTMLDivElement>()
const status = ref('Loading tree...')
const step = ref(0)
const maxStep = ref(0)
const maturity = ref(0)
const playing = ref(false)

let scene: TreeScene | null = null
let timer: ReturnType<typeof setInterval> | null = null
let cancelled = false

async function fetchJson(path: string) {
  const r = await fetch(withBase(path))
  if (!r.ok) throw new Error(`${path}: ${r.status}`)
  return r.json()
}

/** The tile a block is drawn with: its side (or only) texture. */
function tileOf(block: any, prefer: string[]): string | null {
  const textures = block?.model?.textures ?? {}
  for (const k of prefer) if (textures[k]) return textures[k]
  return Object.values<string>(textures)[0] ?? null
}

async function mount() {
  if (!host.value) return
  try {
    let data: TreeData
    try {
      data = await fetchJson(`/data/trees/${props.id}.json`)
    } catch {
      status.value = 'Growth data is generated by the .NET exporter (npm run trees in wiki/), which has not been run here.'
      return
    }
    const [blocks, trees] = await Promise.all([fetchJson('/data/blocks.json'), fetchJson('/data/trees.json')])
    const species = trees[props.id]
    const wood = tileOf(blocks[String(species.wood).replace(/^block\//, '')], ['side', 'all'])
    const leaves = species.leaves ? tileOf(blocks[String(species.leaves).replace(/^block\//, '')], ['all', 'side']) : null
    if (!wood) throw new Error('wood tile not found')
    scene = await buildTree(host.value, data, { wood, leaves, ground: tileOf(blocks.grass, ['top']) ?? 'grass_top' }, withBase('/assets'))
    if (cancelled) { scene.dispose(); return }
    maxStep.value = data.maxStep
    maturity.value = data.maturity
    // Opens as the world's tree (the mature step); ?step=N links to any step.
    const asked = Number(new URLSearchParams(location.search).get('step'))
    const start = Number.isInteger(asked) && new URLSearchParams(location.search).has('step') ? Math.min(Math.max(asked, 0), data.maxStep) : data.maturity
    step.value = start
    scene.setStep(start)
    status.value = ''
  } catch (e) {
    status.value = `3D preview unavailable (${(e as Error).message})`
  }
}

function stop() {
  playing.value = false
  if (timer) clearInterval(timer)
  timer = null
}
function onSlide() { stop(); scene?.setStep(step.value) }
function jump(n: number) { stop(); step.value = n; scene?.setStep(n) }
function togglePlay() {
  if (playing.value) { stop(); return }
  if (step.value >= maxStep.value) step.value = 0
  playing.value = true
  timer = setInterval(() => {
    if (step.value >= maxStep.value) { stop(); return }
    step.value++
    scene?.setStep(step.value)
  }, 70)
}

onMounted(() => {
  const io = new IntersectionObserver((entries) => {
    if (entries[0].isIntersecting && !scene && !cancelled) { io.disconnect(); mount() }
  })
  if (host.value) io.observe(host.value)
  onBeforeUnmount(() => io.disconnect())
})
onBeforeUnmount(() => { cancelled = true; stop(); scene?.dispose() })
</script>

<template>
  <div class="tree-viewer">
    <div ref="host" class="tv-canvas" />
    <p v-if="status" class="tv-status">{{ status }}</p>
    <div v-if="maxStep" class="tv-controls">
      <button type="button" @click="togglePlay">{{ playing ? 'Pause' : step >= maxStep ? 'Replay' : 'Play' }}</button>
      <label class="tv-slider">Growth progress
        <input v-model.number="step" type="range" min="0" :max="maxStep" step="1" @input="onSlide" />
      </label>
      <span class="tv-step">step {{ step }} / {{ maxStep }}</span>
      <button type="button" @click="jump(maturity)">Mature (step {{ maturity }})</button>
      <button type="button" @click="jump(0)">Sapling</button>
    </div>
    <p class="tv-hint">Drag to rotate, scroll to zoom. The trunk thickens and the crown fills in as the tree grows.</p>
  </div>
</template>

