using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Numerics;
using System.Runtime.InteropServices;
using System.Threading;
using VoxelEngine.Content.Blocks;
using VoxelEngine.Data;
using VoxelEngine.Networking;
using VoxelEngine.WorldGen;
using Xunit;

namespace VoxelEngine.Tests.Networking;

/// <summary>
/// A multiplayer client meshes a streamed chunk exactly as the server's own worldgen-backed build
/// does: given the same blocks and the same column terrain (heights, water levels and corner
/// climate), a build reading the <see cref="ClientChunkStreamer"/> as its
/// <see cref="IColumnSource"/> produces the byte-identical mesh one reading
/// <see cref="WorldgenColumnSource"/> does. That covers the light seeding, the water-surface codes
/// of a floor deeper than the build's snapshot and the biome tint, which are everything the mesher
/// reads from terrain beyond the blocks.
/// </summary>
/// <remarks>
/// The helpers here (finding a target, generating its neighbourhood, capturing what a server would
/// stream, comparing meshes) are shared with <see cref="ClientWorldgenIsolationTests"/>.
/// </remarks>
[Collection("Worldgen seed")]
public sealed class StreamedTerrainMeshTests
{
    public StreamedTerrainMeshTests() => TestContent.EnsureLoaded();

    /// <summary>Which terrain a fact meshes.</summary>
    public enum Target
    {
        /// <summary>A dry, biome-tinted surface (grass) near the origin, with air above its top.</summary>
        Surface,

        /// <summary>
        /// A deep ocean floor: the chunk holding the column's highest floor cell, with every
        /// column's water still standing above the build's padded top row, so the floor faces
        /// resolve their water surface from the column's water level rather than the snapshot.
        /// </summary>
        Submerged,
    }

    // Chunk-column rings searched around the origin for a target before giving up.
    private const int SearchRadius = 256;

    private static int ColumnIndex(int lx, int lz) => (lx << Chunk.SizeShift) | lz;

    [Theory]
    [InlineData(Target.Surface)]
    [InlineData(Target.Submerged)]
    public void MeshFromStreamedColumnsEqualsMeshFromWorldgen(Target target)
    {
        var (centre, _) = FindTarget(target, withoutSeedHashedCells: false);

        // The server side: the 27 chunks generated by worldgen, meshed over the worldgen columns
        var worldgen = GenerateNeighbourhood(centre);
        var expected = worldgen.Chunks[centre].GenerateMeshData(worldgen, greedy: true);
        Assert.NotNull(expected);

        // The client side: the same chunks and columns, only as they come off the wire
        var client = new ChunkManager(null!) { Headless = true };
        var streamer = new ClientChunkStreamer(client, (_, _, _) => { }, (_, _) => { });
        StreamChunks(streamer, CaptureChunks(worldgen, centre));
        StreamColumns(streamer, CaptureColumns(centre));
        var actual = client.Chunks[centre].GenerateMeshData(client, greedy: true);
        Assert.NotNull(actual);

        AssertExercises(target, centre, expected);
        AssertSameMesh(expected, actual);
    }

    /// <summary>
    /// Fails unless the target's mesh really ran the rule it stands for: a tinted surface carries
    /// biome-tinted vertices, and a submerged floor carries a face whose baked water surface lies
    /// above the build's padded top row (only the column's water level can put it there).
    /// </summary>
    internal static void AssertExercises(Target target, Vector3 centre, ChunkMeshData mesh)
    {
        if (target == Target.Surface)
        {
            Assert.Contains(mesh.Vertices, v => v.IsBiomeTinted);
            return;
        }

        var paddedTop = ((int)centre.Y + 1) * Chunk.Size;
        Assert.Contains(mesh.Vertices, v => v.IsSubmerged && (v.PackedColor >> 24) != 254
                                            && Vertex.DecodeWaterSurface(v.WaterSurface) > paddedTop);
    }

    /// <summary>
    /// The nearest chunk (in chunk-column rings around the origin) that suits
    /// <paramref name="target"/> under the current seed, and the world cell of its surface top.
    /// <paramref name="withoutSeedHashedCells"/> also requires the chunk to hold no pebble,
    /// branch-pile or layered-snow cell: those emitters draw untouched cells from hashes of the
    /// world seed, so only a chunk without them meshes the same under any seed.
    /// </summary>
    internal static (Vector3 Centre, Vector3 Top) FindTarget(Target target, bool withoutSeedHashedCells)
    {
        for (var r = 0; r <= SearchRadius; r++)
        for (var cx = -r; cx <= r; cx++)
        for (var cz = -r; cz <= r; cz++)
        {
            if (Math.Max(Math.Abs(cx), Math.Abs(cz)) != r)
                continue;
            var found = target == Target.Surface
                ? TrySurface(cx, cz, out var centre, out var top)
                : TrySubmerged(cx, cz, out centre, out top);
            if (found && (!withoutSeedHashedCells || !HasSeedHashedCells(centre)))
                return (centre, top);
        }

        Assert.Fail($"no {target} chunk within {SearchRadius} chunk columns of the origin");
        return default;
    }

    // A dry column whose centre top is a biome-tinted block with two cells of air above it, all
    // inside one chunk (the edit fact re-places the top and stacks a block on it).
    private static bool TrySurface(int cx, int cz, out Vector3 centre, out Vector3 top)
    {
        centre = default;
        top = default;
        var column = ColumnCache.Get(cx, cz);
        var i = ColumnIndex(8, 8);
        var h = column.Heights[i];
        if (column.WaterLevel[i] >= h || (h & Chunk.SizeMask) >= Chunk.Size - 2)
            return false;

        centre = new Vector3(cx, h >> Chunk.SizeShift, cz);
        var chunk = new Chunk(null!, centre, generateBlockData: true);
        var ly = h & Chunk.SizeMask;
        if (BlockType.ById[chunk.GetLocalBlock(8, ly, 8)]?.BiomeTint == null
            || chunk.GetLocalBlock(8, ly + 1, 8) != BlockType.Air
            || chunk.GetLocalBlock(8, ly + 2, 8) != BlockType.Air)
            return false;

        top = new Vector3((cx << Chunk.SizeShift) + 8, h, (cz << Chunk.SizeShift) + 8);
        return true;
    }

    // An ocean column whose highest floor cell still lies a whole chunk row under every one of its
    // columns' water: the padded top row of the floor's chunk is water everywhere.
    private static bool TrySubmerged(int cx, int cz, out Vector3 centre, out Vector3 top)
    {
        centre = default;
        top = default;
        // A cheap single-point pre-filter before computing the whole column
        if (TerrainGenerator.BiomeAt((cx << Chunk.SizeShift) + 8, (cz << Chunk.SizeShift) + 8) != Biome.Ocean)
            return false;

        var column = ColumnCache.Get(cx, cz);
        if (column.MaxWaterLevel == TerrainGenerator.NoWater)
            return false;
        var cy = column.MaxHeight >> Chunk.SizeShift;
        var paddedTop = (cy + 1) * Chunk.Size;
        var highest = -1;
        for (var i = 0; i < column.Heights.Length; i++)
        {
            // Strictly under the top water cell, which a cold sea may have frozen to ice
            if (column.WaterLevel[i] == TerrainGenerator.NoWater || column.WaterLevel[i] <= paddedTop)
                return false;
            if (column.Heights[i] == column.MaxHeight)
                highest = i;
        }

        centre = new Vector3(cx, cy, cz);
        top = new Vector3((cx << Chunk.SizeShift) + (highest >> Chunk.SizeShift), column.MaxHeight,
            (cz << Chunk.SizeShift) + (highest & Chunk.SizeMask));
        return true;
    }

    // Whether any cell of the chunk is drawn by an emitter that hashes the world seed.
    private static bool HasSeedHashedCells(Vector3 pos)
    {
        var chunk = new Chunk(null!, pos, generateBlockData: true);
        for (var x = 0; x < Chunk.Size; x++)
        for (var y = 0; y < Chunk.Size; y++)
        for (var z = 0; z < Chunk.Size; z++)
        {
            var renderer = BlockType.ById[chunk.GetLocalBlock(x, y, z)]?.Renderer;
            if (renderer is BlockRenderer.Pebbles or BlockRenderer.BranchPile or BlockRenderer.SnowLayers)
                return true;
        }

        return false;
    }

    /// <summary>A worldgen chunk manager holding the 3x3x3 chunks around <paramref name="centre"/>,
    /// generated through the real factory.</summary>
    internal static ChunkManager GenerateNeighbourhood(Vector3 centre)
    {
        var manager = new ChunkManager(null!);
        foreach (var pos in Neighbourhood(centre))
            manager.QueueChunk(pos);
        return manager;
    }

    private static IEnumerable<Vector3> Neighbourhood(Vector3 centre)
    {
        for (var dx = -1; dx <= 1; dx++)
        for (var dy = -1; dy <= 1; dy++)
        for (var dz = -1; dz <= 1; dz++)
            yield return centre + new Vector3(dx, dy, dz);
    }

    /// <summary>The 27 chunks around <paramref name="centre"/> as a server sends them
    /// (<see cref="ChunkNetCodec.Encode"/> of <see cref="ChunkManager.TryCaptureChunk"/>).</summary>
    internal static List<(Vector3 Pos, byte[] Payload)> CaptureChunks(ChunkManager manager, Vector3 centre)
    {
        var chunks = new List<(Vector3, byte[])>();
        foreach (var pos in Neighbourhood(centre))
        {
            Assert.True(manager.TryCaptureChunk((int)pos.X, (int)pos.Y, (int)pos.Z, out var snapshot), $"{pos} is not loaded");
            chunks.Add((pos, ChunkNetCodec.Encode(snapshot)));
        }

        return chunks;
    }

    /// <summary>The nine column payloads around <paramref name="centre"/> exactly as the server
    /// answers a column request: its own <see cref="WorldgenColumnSource"/> value, encoded.</summary>
    internal static List<(int X, int Z, byte[] Payload)> CaptureColumns(Vector3 centre)
    {
        var columns = new List<(int, int, byte[])>();
        for (var dx = -1; dx <= 1; dx++)
        for (var dz = -1; dz <= 1; dz++)
        {
            var cx = (int)centre.X + dx;
            var cz = (int)centre.Z + dz;
            Assert.True(WorldgenColumnSource.Instance.TryGet(cx, cz, out var terrain));
            columns.Add((cx, cz, ChunkNetCodec.EncodeColumn(terrain)));
        }

        return columns;
    }

    internal static void StreamChunks(ClientChunkStreamer streamer, List<(Vector3 Pos, byte[] Payload)> chunks)
    {
        foreach (var (pos, payload) in chunks)
            streamer.ApplyChunk((int)pos.X, (int)pos.Y, (int)pos.Z, payload);
    }

    internal static void StreamColumns(ClientChunkStreamer streamer, List<(int X, int Z, byte[] Payload)> columns)
    {
        foreach (var (x, z, payload) in columns)
            streamer.ApplyColumn(x, z, payload);
    }

    /// <summary>Two builds' outputs are the same bytes: vertices, indices, the published light and
    /// the hot-fluid vents.</summary>
    internal static void AssertSameMesh(ChunkMeshData expected, ChunkMeshData actual)
    {
        AssertSameVertices(expected.Vertices, actual.Vertices, "opaque");
        Assert.Equal(expected.Indices, actual.Indices);
        AssertSameVertices(expected.TranslucentVertices, actual.TranslucentVertices, "translucent");
        Assert.Equal(expected.TranslucentIndices, actual.TranslucentIndices);
        Assert.Equal(expected.HasWater, actual.HasWater);
        Assert.Equal(expected.Light, actual.Light);
        Assert.Equal(expected.HotFluidVents, actual.HotFluidVents);
    }

    private static void AssertSameVertices(List<Vertex> expected, List<Vertex> actual, string list)
    {
        Assert.True(expected.Count == actual.Count,
            $"{list} vertex count differs: expected {expected.Count}, got {actual.Count}");
        var a = MemoryMarshal.AsBytes(CollectionsMarshal.AsSpan(expected));
        var b = MemoryMarshal.AsBytes(CollectionsMarshal.AsSpan(actual));
        if (a.SequenceEqual(b))
            return;
        var first = a.CommonPrefixLength(b) / (int)Vertex.Size;
        Assert.Fail($"{list} vertex {first} differs: expected at {expected[first].Position} " +
                    $"rgba {expected[first].PackedColor:X8} sun {expected[first].Sun} surface {expected[first].WaterSurface}, " +
                    $"got at {actual[first].Position} rgba {actual[first].PackedColor:X8} sun {actual[first].Sun} " +
                    $"surface {actual[first].WaterSurface}");
    }

    /// <summary>Whether <paramref name="manager"/> has no mesh work queued or in flight.</summary>
    internal static bool Quiescent(ChunkManager manager) =>
        manager.GeneratingMeshCount == 0 && manager.PendingMeshWorkCount == 0 && manager.ActiveMeshRunnerCount == 0;

    internal static bool WaitUntil(Func<bool> done, int timeoutMs = 15000)
    {
        var sw = Stopwatch.StartNew();
        while (sw.ElapsedMilliseconds < timeoutMs)
        {
            if (done()) return true;
            Thread.Sleep(1);
        }

        return done();
    }
}
