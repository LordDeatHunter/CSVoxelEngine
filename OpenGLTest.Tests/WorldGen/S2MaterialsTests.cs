using System;
using System.Collections.Generic;
using System.Numerics;
using VoxelEngine.Content;
using VoxelEngine.Lod;
using VoxelEngine.WorldGen;
using Xunit;
using Xunit.Abstractions;

namespace VoxelEngine.Tests.WorldGen;

/// <summary>Actual generated canyon material controls for Dynamic strata.</summary>
[Collection("Worldgen seed")]
public sealed class S2MaterialsTests(ITestOutputHelper output)
{
    [Fact]
    public void RealBareAridCanyonExposesSedimentaryBand()
    {
        TestContent.EnsureLoaded();
        var probes = 0;
        var chunks = 0;
        try
        {
            WorldSeed.Apply(WorldSeed.Default, WorldGenProfile.Dynamic);
            const int x = -4000;
            const int z = 5000;
            var column = ColumnCache.Get(x >> Chunk.SizeShift, z >> Chunk.SizeShift);
            probes++;
            var local = ((x & Chunk.SizeMask) << Chunk.SizeShift) | (z & Chunk.SizeMask);
            Assert.Equal(0, column.DirtDepth[local]);
            Assert.Equal(Biome.Savanna, column.Biomes[local]);
            Assert.True(column.Heights[local] > 80);
            var chunk = new Chunk(null!, new Vector3(x >> Chunk.SizeShift, 5, z >> Chunk.SizeShift),
                generateBlockData: false);
            ChunkTerrainFill.GenerateBlockData(chunk);
            chunks++;
            var ids = new HashSet<ushort>();
            for (var y = 80; y <= column.Heights[local]; y++)
            {
                probes++;
                ids.Add(chunk.Storage.Get(Chunk.Idx(x & Chunk.SizeMask, y & Chunk.SizeMask,
                    z & Chunk.SizeMask)));
            }
            var sandstone = ContentRegistry.RequireBlock("sandstone").Id;
            var ochre = ContentRegistry.RequireBlock("ochre_clay").Id;
            output.WriteLine($"real bare Savanna canyon ({x},{z}) top {column.Heights[local]} IDs {string.Join(",", ids)}");
            Assert.Equal(TerrainGenerator.RockBlock,
                chunk.Storage.Get(Chunk.Idx(x & Chunk.SizeMask, column.Heights[local] & Chunk.SizeMask,
                    z & Chunk.SizeMask)));
            Assert.Contains(sandstone, ids);
            Assert.Contains(ochre, ids);
        }
        finally
        {
            output.WriteLine($"S2 materials direct entries={probes}, new chunks={chunks}");
            WorldSeed.Apply(WorldSeed.Default);
        }
    }

    [Fact]
    public void BareWallBandsRepeatAfterProfileResetWhileLegacyAndSoilStayUnchanged()
    {
        TestContent.EnsureLoaded();
        var probes = 0;
        var chunks = 0;
        try
        {
            const int x = -4000;
            const int z = 5000;
            var newIds = new HashSet<ushort>
            {
                ContentRegistry.RequireBlock("red_sandstone").Id,
                ContentRegistry.RequireBlock("ochre_clay").Id,
            };
            WorldSeed.Apply(WorldSeed.Default, WorldGenProfile.Dynamic);
            var first = Sample(x, z, ref probes, ref chunks);
            Assert.Contains(first, id => newIds.Contains(id));

            WorldSeed.Apply(WorldSeed.Default, WorldGenProfile.Legacy);
            var old = Sample(x, z, ref probes, ref chunks);
            Assert.DoesNotContain(old, id => newIds.Contains(id));

            WorldSeed.Apply(WorldSeed.Default, WorldGenProfile.Dynamic);
            Assert.Equal(first, Sample(x, z, ref probes, ref chunks));

            // The spawn's ordinary Forest soil is generated by the same fill path.
            var soil = Sample(0, 0, ref probes, ref chunks);
            Assert.DoesNotContain(soil, id => newIds.Contains(id));
        }
        finally
        {
            output.WriteLine($"S2 materials direct entries={probes}, new chunks={chunks}");
            WorldSeed.Apply(WorldSeed.Default);
        }
    }

    private static ushort[] Sample(int x, int z, ref int probes, ref int chunks)
    {
        var column = ColumnCache.Get(x >> Chunk.SizeShift, z >> Chunk.SizeShift);
        probes++;
        var local = ((x & Chunk.SizeMask) << Chunk.SizeShift) | (z & Chunk.SizeMask);
        var chunkY = column.Heights[local] >> Chunk.SizeShift;
        var chunk = new Chunk(null!, new Vector3(x >> Chunk.SizeShift, chunkY, z >> Chunk.SizeShift),
            generateBlockData: false);
        ChunkTerrainFill.GenerateBlockData(chunk);
        chunks++;
        var result = new ushort[Chunk.Size];
        for (var y = 0; y < Chunk.Size; y++)
        {
            result[y] = chunk.Storage.Get(Chunk.Idx(x & Chunk.SizeMask, y, z & Chunk.SizeMask));
            probes++;
        }
        return result;
    }

    [Fact]
    public void GeneratedCanyonLodShowsTheNewWallPalette()
    {
        TestContent.EnsureLoaded();
        var probes = 0;
        try
        {
            WorldSeed.Apply(WorldSeed.Default, WorldGenProfile.Dynamic);
            var spec = LodRegion.Levels[0];
            var rx = (int)MathF.Floor(-4000f / spec.RegionBlocks);
            var rz = (int)MathF.Floor(5000f / spec.RegionBlocks);
            var mesh = LodRegion.BuildMeshData(0, rx, rz);
            probes += spec.Cells * spec.Cells;
            var red = VoxelEngine.BlockType.ById[ContentRegistry.RequireBlock("red_sandstone").Id]!.FaceTiles[0];
            var ochre = VoxelEngine.BlockType.ById[ContentRegistry.RequireBlock("ochre_clay").Id]!.FaceTiles[0];
            var wallFaces = 0;
            foreach (var vertex in mesh.Vertices)
            {
                if ((vertex.Normal & 7) == 4) continue;
                if (vertex.Layer == red || vertex.Layer == ochre) wallFaces++;
            }
            output.WriteLine($"generated canyon LOD colored wall vertices={wallFaces}; direct cell entries={probes}");
            Assert.True(wallFaces > 0);
        }
        finally
        {
            output.WriteLine($"S2 materials direct entries={probes}, new chunks=0");
            WorldSeed.Apply(WorldSeed.Default);
        }
    }
}
